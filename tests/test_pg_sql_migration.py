def test_postgresql_types_map_to_mssql_and_oracle():
    integer, _note, error = map_column("mssql", {"data_type": "integer"})
    assert integer == "INT" and error is None
    varchar, _note, error = map_column("mssql", {"data_type": "character varying", "character_maximum_length": 40})
    assert varchar == "NVARCHAR(40)" and error is None
    jsonb, lossy, error = map_column("mssql", {"data_type": "jsonb"})
    assert jsonb == "NVARCHAR(MAX)" and lossy and error is None
    number, _note, error = map_column("oracle", {"data_type": "bigint"})
    assert number == "NUMBER(19)" and error is None
    text, _note, error = map_column("oracle", {"data_type": "text"})
    assert text == "CLOB" and error is None
    unknown, _note, error = map_column("mssql", {"data_type": "array"})
    assert unknown is None and "cannot be mapped" in error
    assert quote_ident("mssql", "ord]ers") == "[ord]]ers]"
    assert placeholder("mssql", 1) == "?"
    assert placeholder("oracle", 2) == ":2"
    assert adapt_value(True, "BIT") == 1
    assert adapt_value(False, "NUMBER(1)") == 0


def test_create_and_insert_sql_use_the_target_dialect():
    spec = TableSpec(
        "orders",
        columns=[ColumnSpec("id", "INT", False, True), ColumnSpec("note", "NVARCHAR(MAX)", True)],
        primary_key=["id"],
    )
    mssql = create_table_sql("mssql", spec)
    assert 'CREATE TABLE [orders]' in mssql
    assert "[id] INT IDENTITY(1,1) NOT NULL" in mssql
    assert insert_sql("mssql", spec) == "INSERT INTO [orders] ([id], [note]) VALUES (?, ?)"
    oracle_spec = TableSpec(
        "orders",
        columns=[ColumnSpec("id", "NUMBER(10)", False, True), ColumnSpec("note", "CLOB", True)],
        primary_key=["id"],
    )
    oracle = create_table_sql("oracle", oracle_spec)
    assert 'CREATE TABLE "orders"' in oracle
    assert 'GENERATED BY DEFAULT AS IDENTITY' in oracle
    assert insert_sql("oracle", oracle_spec) == 'INSERT INTO "orders" ("id", "note") VALUES (:1, :2)'


class _Target:
    def __init__(self):
        self.statements = []
        self.batches = []
        self.commits = 0

    def execute(self, sql, params=None):
        self.statements.append(sql)

    def executemany(self, sql, rows):
        self.batches.append(list(rows))

    def query(self, sql, params=None):
        return [{"row_count": sum(len(batch) for batch in self.batches)}]

    def commit(self):
        self.commits += 1

    def rollback(self):
        pass


def test_postgresql_rows_are_inserted_into_sql_server():
    spec = TableSpec(
        "orders",
        columns=[ColumnSpec("id", "INT", False, True), ColumnSpec("flag", "BIT", True)],
        primary_key=["id"],
    )
    target = _Target()

    def fetch(_table, _columns, _batch, _cancel):
        yield [(1, True), (2, False)]

    result = run_pg_sql_migration(
        [spec], [], target_kind="mssql", scope=SCOPE_SCHEMA_AND_DATA, strategy=STRATEGY_SKIP,
        batch_size=2, fetch_batches=fetch, target=target, count_source=lambda _name: 2,
        cancel=threading.Event(), migration_id="pg-mssql-1",
    )
    assert result.status == "Completed and verified"
    assert any(sql.startswith("CREATE TABLE [orders]") for sql in target.statements)
    assert any("IDENTITY_INSERT [orders] ON" in sql for sql in target.statements)
    assert target.batches == [[(1, 1), (2, 0)]]


def test_existing_oracle_table_can_be_skipped():
    spec = TableSpec("orders", columns=[ColumnSpec("id", "NUMBER(10)", False)], primary_key=["id"])
    target = _Target()
    result = run_pg_sql_migration(
        [spec], ["orders"], target_kind="oracle", scope=SCOPE_SCHEMA_AND_DATA, strategy=STRATEGY_SKIP,
        batch_size=10, fetch_batches=lambda *_args: iter(()), target=target, count_source=lambda _name: 0,
        cancel=threading.Event(), migration_id="pg-oracle-skip",
    )
    assert result.status == "Completed with warnings"
    assert result.outcomes[0].action == "skipped"
    assert target.statements == []


def test_precheck_accepts_sql_server_and_builds_a_plan():
    source_columns = [
        {
            "column_name": "id",
            "data_type": "integer",
            "udt_name": "int4",
            "is_nullable": "NO",
            "identity_generation": "BY DEFAULT",
            "column_default": None,
        }
    ]

    def source_query(sql):
        text = sql.lower()
        if "version()" in text:
            return [{"version": "PostgreSQL 16", "database_name": "shop"}]
        if "pg_class" in text:
            return [{"table_name": "orders"}]
        if "information_schema.columns" in text:
            return source_columns
        if "primary key" in text:
            return [{"column_name": "id"}]
        return []

    def target_query(sql):
        text = sql.lower()
        if "@@version" in text:
            return [{"version": "Microsoft SQL Server 2019", "database_name": "master"}]
        if "sys.databases" in text:
            return []
        return []

    report = assess_pg_sql(
        source_query,
        target_query,
        target_kind="mssql",
        scope=SCOPE_SCHEMA,
        selected_tables=None,
        strategy=STRATEGY_SKIP,
        confirm_replace=False,
        accept_unproven_backup=True,
        batch_size=100,
        statement_timeout_ms=0,
        expected_database="shop_copy",
    )
    assert report.ready
    assert report.engine == "postgresql_to_mssql"
    assert report.dest_will_create
    assert report.tables == ["orders"]
    plan = build_pg_sql_plan(report, scope=SCOPE_SCHEMA, strategy=STRATEGY_SKIP, batch_size=100, statement_timeout_ms=0)
    assert "PostgreSQL to SQL Server" in plan.text
    started = start_pg_sql_migration(
        plan, confirmed=True, operator="tester",
        fetch_batches=lambda *_args: iter(()), target=_Target(),
        count_source=lambda _name: 0, cancel=threading.Event(),
    )
    assert started.status == "Completed and verified"


def test_load_table_blocks_unmapped_postgresql_types():
    def source_query(sql):
        if "information_schema.columns" in sql.lower():
            return [{"column_name": "points", "data_type": "array", "udt_name": "_int4", "is_nullable": "YES"}]
        return []

    spec = load_table("oracle", source_query, "points")
    assert spec.blocked
    assert "was not mapped" in spec.blocked
