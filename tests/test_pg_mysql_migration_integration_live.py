def test_live_cancel_does_not_claim_the_created_table_was_rolled_back():
    import threading

    pg, my = _live_pair()
    try:
        with pg.cursor() as cursor:
            cursor.execute("DROP TABLE IF EXISTS cancel_probe CASCADE")
            cursor.execute("CREATE TABLE cancel_probe (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, note text)")
            cursor.execute("INSERT INTO cancel_probe (note) VALUES ('a'), ('b'), ('c')")
        _drop_mysql(my, "cancel_probe")
        token = threading.Event()

        def fetch(table, columns, size, cancel):
            from backend.services.pg_migration.precheck import quote_ident

            column_sql = ", ".join(quote_ident(name) for name in columns)
            read_conn = psycopg2_connect()
            cursor = read_conn.cursor(name="pgmysql_cancel")
            try:
                cursor.itersize = size
                cursor.execute(f"SELECT {column_sql} FROM public.{quote_ident(table)}")
                first = True
                while True:
                    rows = cursor.fetchmany(size)
                    if not rows:
                        return
                    if not first:
                        cancel.set()
                    first = False
                    yield rows
            finally:
                cursor.close()
                read_conn.close()

        result = _migrate(pg, my, ["cancel_probe"], "schema_and_data", batch_size=1, fetch=fetch, cancel=token)
        assert result.status == "Cancelled", result.summary
        assert "not rolled back" in result.summary
        assert "fully rolled back" not in result.summary.lower()
        cursor = my.cursor()
        cursor.execute("SELECT COUNT(*) FROM `cancel_probe`")
        assert int(cursor.fetchone()[0]) == 0
        cursor.close()
    finally:
        with pg.cursor() as cursor:
            cursor.execute("DROP TABLE IF EXISTS cancel_probe CASCADE")
        pg.close()
        _drop_mysql(my, "cancel_probe")
        my.close()


