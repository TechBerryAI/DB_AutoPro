def test_live_killed_process_requires_reconciliation_and_does_not_rerun(tmp_path):
    import subprocess
    import sys
    import time

    import mysql.connector

    from backend.core.exceptions import MigrationRejected
    from backend.services.pg_mysql_migration.operation_store import MigrationOperationStore

    pg, my = _live_pair()
    target_setup = _parse(TARGET_DSN)
    process = None
    stderr_file = None
    try:
        with pg.cursor() as cursor:
            cursor.execute("DROP TABLE IF EXISTS kill_hold CASCADE")
            cursor.execute("CREATE TABLE kill_hold (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)")
        _drop_mysql(my, "kill_hold")
        my.close()
        my = None
        store_path = tmp_path / "kill.sqlite"
        stderr_path = tmp_path / "kill-worker.err"
        env = os.environ.copy()
        env["DB_AUTOPRO_PGMYSQL_KILL_STORE"] = str(store_path)
        stderr_file = stderr_path.open("w", encoding="utf-8")
        process = subprocess.Popen(
            [sys.executable, "-m", "tests.pgmysql_kill_worker"],
            cwd=os.path.abspath(os.path.join(os.path.dirname(__file__), "..")),
            env=env,
            stdout=subprocess.DEVNULL,
            stderr=stderr_file,
        )
        deadline = time.time() + 40
        visible = False
        while time.time() < deadline:
            check = mysql.connector.connect(
                host=target_setup["host"],
                port=target_setup["port"],
                user=target_setup["user"],
                password=target_setup["password"],
                database=target_setup["database"],
            )
            try:
                cursor = check.cursor()
                cursor.execute("SHOW TABLES LIKE 'kill_hold'")
                visible = bool(cursor.fetchall())
                cursor.close()
            finally:
                check.close()
            if visible and store_path.exists():
                running = MigrationOperationStore(store_path).get_by_client_request("kill-hold")
                if running and running["status"] == "running":
                    break
            if process.poll() is not None:
                stderr_file.close()
                detail = _redacted_log(stderr_path)
                raise AssertionError("kill worker exited before the operation was running: " + detail)
            time.sleep(0.1)
        else:
            stderr_file.close()
            detail = _redacted_log(stderr_path)
            raise AssertionError("killed migration did not leave a running operation: " + detail)
        process.kill()
        process.wait(timeout=15)
        process = None
        stderr_file.close()
        store = MigrationOperationStore(store_path)
        assert store.reconcile_interrupted() == 1
        saved = store.get_by_client_request("kill-hold")
        assert saved["status"] == "reconciliation_required"
        assert "Do not assume MySQL changes were rolled back" in saved["recovery"]
        from backend.connectors.base import ConnectionInfo
        from backend.connectors.mysql import MySQLConnector
        from backend.connectors.postgresql import PostgreSQLConnector
        from backend.models.schemas import DatabaseType, MigrationRequest
        from backend.services.migration_service import MigrationService

        source = _parse(SOURCE_DSN)
        target = _parse(TARGET_DSN)

        def factory(db_type, _profile):
            if db_type == DatabaseType.POSTGRESQL:
                return PostgreSQLConnector(
                    ConnectionInfo(source["host"], source["port"], source["database"], source["user"], source["password"])
                )
            return MySQLConnector(
                ConnectionInfo(target["host"], target["port"], target["database"], target["user"], target["password"])
            )

        service = MigrationService(factory, store)
        try:
            service.migrate(
                MigrationRequest(
                    source_type=DatabaseType.POSTGRESQL,
                    target_type=DatabaseType.MYSQL,
                    scope="schema_only",
                    strategy="skip_existing",
                    source_database=SOURCE_NAME,
                    target_database=TARGET_NAME,
                    tables=["kill_hold"],
                    confirm_plan=True,
                    client_request_id="kill-hold-retry",
                ),
                user="disposable-test",
            )
        except MigrationRejected as exc:
            assert "Reconcile" in str(exc)
            assert "Nothing new was copied." in str(exc)
        else:
            raise AssertionError("startup resumed a killed migration")
        check = mysql.connector.connect(
            host=target["host"],
            port=target["port"],
            user=target["user"],
            password=target["password"],
            database=target["database"],
        )
        try:
            cursor = check.cursor()
            cursor.execute("SELECT COUNT(*) FROM `kill_hold`")
            assert int(cursor.fetchone()[0]) == 0
            cursor.close()
        finally:
            check.close()
    finally:
        if process is not None and process.poll() is None:
            process.kill()
            process.wait(timeout=15)
        if stderr_file is not None and not stderr_file.closed:
            stderr_file.close()
        with pg.cursor() as cursor:
            cursor.execute("DROP TABLE IF EXISTS kill_hold CASCADE")
        pg.close()
        if my is not None:
            _drop_mysql(my, "kill_hold")
            my.close()
        else:
            cleanup = mysql.connector.connect(
                host=target_setup["host"],
                port=target_setup["port"],
                user=target_setup["user"],
                password=target_setup["password"],
                database=target_setup["database"],
            )
            try:
                _drop_mysql(cleanup, "kill_hold")
            finally:
                cleanup.close()

