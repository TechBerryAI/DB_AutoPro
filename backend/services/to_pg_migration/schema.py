"""Read source tables or collections and render PostgreSQL DDL."""

from __future__ import annotations

from dataclasses import dataclass, field

from backend.services.to_pg_migration.mapping import map_column, quote_pg


@dataclass
class ColumnSpec:
    name: str
    pg_type: str
    nullable: bool
    auto_increment: bool = False
    lossy: str | None = None


@dataclass
class TableSpec:
    name: str
    columns: list[ColumnSpec] = field(default_factory=list)
    primary_key: list[str] = field(default_factory=list)
    blocked: str = ""
    conversions: list[str] = field(default_factory=list)
    kind: str = "table"


def create_table_sql(table: TableSpec) -> str:
    parts: list[str] = []
    for column in table.columns:
        null_sql = "NULL" if column.nullable else "NOT NULL"
        identity = " GENERATED BY DEFAULT AS IDENTITY" if column.auto_increment else ""
        parts.append(f"{quote_pg(column.name)} {column.pg_type} {null_sql}{identity}")
    if table.primary_key:
        parts.append("PRIMARY KEY (" + ", ".join(quote_pg(name) for name in table.primary_key) + ")")
    return f"CREATE TABLE {quote_pg(table.name)} (" + ", ".join(parts) + ")"


def insert_sql(table: TableSpec) -> str:
    columns = ", ".join(quote_pg(column.name) for column in table.columns)
    placeholders = ", ".join(["%s"] * len(table.columns))
    return f"INSERT INTO {quote_pg(table.name)} ({columns}) VALUES ({placeholders})"


def drop_table_sql(name: str) -> str:
    return f"DROP TABLE IF EXISTS {quote_pg(name)} CASCADE"


def count_sql(name: str) -> str:
    return f"SELECT count(*) AS row_count FROM {quote_pg(name)}"


def mongo_spec(name: str) -> TableSpec:
    spec = TableSpec(
        name=name,
        columns=[
            ColumnSpec("_id", "TEXT", False),
            ColumnSpec("doc", "JSONB", False),
        ],
        primary_key=["_id"],
        kind="collection",
        conversions=[f"{name}: MongoDB documents are stored as JSONB in column doc. Nested documents are not split into tables."],
    )
    return spec


def load_relational_table(kind: str, source_query, name: str) -> TableSpec:
    from backend.services.migration_framework.registry import _norm

    kind = _norm(kind)
    spec = TableSpec(name=name)
    columns = _columns(kind, source_query, name)
    if not columns:
        spec.blocked = f"Table {name} has no columns."
        return spec
    for column in columns:
        column_name = str(column.get("column_name") or column.get("COLUMN_NAME") or "")
        data_type = str(column.get("data_type") or column.get("DATA_TYPE") or "")
        extra = str(column.get("extra") or column.get("EXTRA") or "").lower()
        identity = str(column.get("is_identity") or "")
        auto = "auto_increment" in extra or str(identity).lower() in {"yes", "1", "true"}
        pg_type, lossy, error = map_column(
            kind,
            data_type,
            length=column.get("character_maximum_length") or column.get("CHAR_LENGTH") or column.get("DATA_LENGTH"),
            precision=column.get("numeric_precision") or column.get("DATA_PRECISION"),
            scale=column.get("numeric_scale") or column.get("DATA_SCALE"),
        )
        if error or not pg_type:
            spec.blocked = f"{name}.{column_name} was not mapped: {error}"
            return spec
        if auto and pg_type.split("(")[0] not in {"SMALLINT", "INTEGER", "BIGINT", "NUMERIC"}:
            spec.blocked = f"{name}.{column_name} is an identity column that PostgreSQL cannot store as IDENTITY."
            return spec
        if lossy:
            spec.conversions.append(f"{name}.{column_name}: {lossy}")
        nullable = str(column.get("is_nullable") or column.get("NULLABLE") or "YES").upper() in {"YES", "Y"}
        spec.columns.append(ColumnSpec(column_name, pg_type, nullable, auto_increment=auto, lossy=lossy))
    spec.primary_key = _primary_key(kind, source_query, name)
    if any(column.auto_increment for column in spec.columns):
        spec.conversions.append(f"{name}: identity or auto-increment becomes GENERATED BY DEFAULT AS IDENTITY.")
    return spec


def _columns(kind: str, source_query, name: str) -> list[dict]:
    if kind == "mysql":
        return source_query(
            "SELECT column_name, data_type, character_maximum_length, numeric_precision, numeric_scale, "
            "is_nullable, extra FROM information_schema.columns "
            f"WHERE table_schema = DATABASE() AND table_name = {_sql(name)} ORDER BY ordinal_position"
        )
    if kind == "mssql":
        return source_query(
            "SELECT c.COLUMN_NAME AS column_name, c.DATA_TYPE AS data_type, c.CHARACTER_MAXIMUM_LENGTH AS character_maximum_length, "
            "c.NUMERIC_PRECISION AS numeric_precision, c.NUMERIC_SCALE AS numeric_scale, c.IS_NULLABLE AS is_nullable, "
            "COLUMNPROPERTY(OBJECT_ID(c.TABLE_SCHEMA + '.' + c.TABLE_NAME), c.COLUMN_NAME, 'IsIdentity') AS is_identity "
            "FROM INFORMATION_SCHEMA.COLUMNS c "
            f"WHERE c.TABLE_NAME = {_sql(name)} AND c.TABLE_SCHEMA = 'dbo' ORDER BY c.ORDINAL_POSITION"
        )
    return source_query(
        "SELECT column_name, data_type, data_length, data_precision, data_scale, nullable AS is_nullable "
        f"FROM user_tab_columns WHERE table_name = {_sql(name.upper())} ORDER BY column_id"
    )


def _primary_key(kind: str, source_query, name: str) -> list[str]:
    try:
        if kind == "mysql":
            rows = source_query(
                "SELECT column_name FROM information_schema.key_column_usage "
                f"WHERE table_schema = DATABASE() AND table_name = {_sql(name)} "
                "AND constraint_name = 'PRIMARY' ORDER BY ordinal_position"
            )
        elif kind == "mssql":
            rows = source_query(
                "SELECT kcu.COLUMN_NAME AS column_name FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc "
                "JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE kcu ON kcu.CONSTRAINT_NAME = tc.CONSTRAINT_NAME "
                f"WHERE tc.CONSTRAINT_TYPE = 'PRIMARY KEY' AND tc.TABLE_NAME = {_sql(name)} "
                "AND tc.TABLE_SCHEMA = 'dbo' ORDER BY kcu.ORDINAL_POSITION"
            )
        else:
            rows = source_query(
                "SELECT cols.column_name FROM user_constraints cons "
                "JOIN user_cons_columns cols ON cons.constraint_name = cols.constraint_name "
                f"WHERE cons.constraint_type = 'P' AND cons.table_name = {_sql(name.upper())} "
                "ORDER BY cols.position"
            )
    except Exception:
        return []
    names = []
    for row in rows or []:
        value = str(row.get("column_name") or row.get("COLUMN_NAME") or "")
        if value:
            names.append(value)
    return names


def list_source_tables(kind: str, source_query) -> list[str]:
    from backend.services.migration_framework.registry import _norm

    kind = _norm(kind)
    if kind == "mysql":
        rows = source_query(
            "SELECT table_name FROM information_schema.tables "
            "WHERE table_schema = DATABASE() AND table_type = 'BASE TABLE' ORDER BY 1"
        )
    elif kind == "mssql":
        rows = source_query(
            "SELECT TABLE_NAME AS table_name FROM INFORMATION_SCHEMA.TABLES "
            "WHERE TABLE_TYPE = 'BASE TABLE' AND TABLE_SCHEMA = 'dbo' ORDER BY 1"
        )
    else:
        rows = source_query("SELECT table_name FROM user_tables ORDER BY 1")
    names = []
    for row in rows or []:
        value = str(row.get("table_name") or row.get("TABLE_NAME") or "")
        if value:
            names.append(value)
    return names


def _sql(value: str) -> str:
    return "'" + str(value).replace("'", "''") + "'"
