"""Read PostgreSQL public tables and render SQL Server or Oracle DDL."""

from __future__ import annotations

from dataclasses import dataclass, field

from backend.services.migration_framework.registry import MSSQL, _norm
from backend.services.pg_sql_migration.mapping import map_column, placeholder, quote_ident


@dataclass
class ColumnSpec:
    name: str
    target_type: str
    nullable: bool
    identity: bool = False
    lossy: str | None = None


@dataclass
class TableSpec:
    name: str
    columns: list[ColumnSpec] = field(default_factory=list)
    primary_key: list[str] = field(default_factory=list)
    blocked: str = ""
    conversions: list[str] = field(default_factory=list)


def create_table_sql(kind: str, table: TableSpec) -> str:
    kind = _norm(kind)
    parts: list[str] = []
    for column in table.columns:
        null_sql = "NULL" if column.nullable else "NOT NULL"
        if column.identity and kind == MSSQL:
            parts.append(f"{quote_ident(kind, column.name)} {column.target_type} IDENTITY(1,1) {null_sql}")
        elif column.identity:
            parts.append(f"{quote_ident(kind, column.name)} {column.target_type} GENERATED BY DEFAULT AS IDENTITY {null_sql}")
        else:
            parts.append(f"{quote_ident(kind, column.name)} {column.target_type} {null_sql}")
    if table.primary_key:
        parts.append("PRIMARY KEY (" + ", ".join(quote_ident(kind, name) for name in table.primary_key) + ")")
    return f"CREATE TABLE {quote_ident(kind, table.name)} (" + ", ".join(parts) + ")"


def insert_sql(kind: str, table: TableSpec) -> str:
    kind = _norm(kind)
    columns = ", ".join(quote_ident(kind, column.name) for column in table.columns)
    values = ", ".join(placeholder(kind, index + 1) for index in range(len(table.columns)))
    return f"INSERT INTO {quote_ident(kind, table.name)} ({columns}) VALUES ({values})"


def drop_table_sql(kind: str, name: str) -> str:
    kind = _norm(kind)
    quoted = quote_ident(kind, name)
    if kind == MSSQL:
        return f"IF OBJECT_ID(N'dbo.{name.replace(chr(39), chr(39) + chr(39))}', N'U') IS NOT NULL DROP TABLE {quoted}"
    return f'DROP TABLE {quoted} CASCADE CONSTRAINTS'


def count_sql(kind: str, name: str) -> str:
    return f"SELECT COUNT(*) AS row_count FROM {quote_ident(kind, name)}"


def load_table(kind: str, source_query, name: str) -> TableSpec:
    kind = _norm(kind)
    literal = "'" + name.replace("'", "''") + "'"
    columns = source_query(
        "SELECT column_name, data_type, udt_name, character_maximum_length, "
        "numeric_precision, numeric_scale, is_nullable, column_default, identity_generation "
        "FROM information_schema.columns "
        f"WHERE table_schema = 'public' AND table_name = {literal} ORDER BY ordinal_position"
    )
    spec = TableSpec(name=name)
    if not columns:
        spec.blocked = f"Table {name} has no columns in schema public."
        return spec
    for column in columns:
        column_name = str(column.get("column_name") or "")
        target_type, lossy, error = map_column(kind, column)
        identity = str(column.get("identity_generation") or "").upper()
        default = column.get("column_default")
        auto = identity in {"ALWAYS", "BY DEFAULT"} or (
            isinstance(default, str) and default.lower().startswith("nextval(")
        )
        if error or not target_type:
            spec.blocked = f"{name}.{column_name} was not mapped: {error}"
            return spec
        if auto and not _identity_type(kind, target_type):
            spec.blocked = (
                f"{name}.{column_name} uses a sequence, and {kind} can apply identity only to a numeric column."
            )
            return spec
        if lossy:
            spec.conversions.append(f"{name}.{column_name}: {lossy}")
        spec.columns.append(
            ColumnSpec(
                name=column_name,
                target_type=target_type,
                nullable=str(column.get("is_nullable") or "YES").upper() == "YES",
                identity=auto,
                lossy=lossy,
            )
        )
    autos = [column.name for column in spec.columns if column.identity]
    if len(autos) > 1:
        spec.blocked = f"{name} has more than one identity column. {kind} allows one identity column."
        return spec
    spec.primary_key = _primary_key(source_query, name)
    if autos and autos[0] not in spec.primary_key:
        spec.blocked = (
            f"{name}.{autos[0]} is an identity column but not part of the primary key. "
            "Identity was not applied, and the table was not migrated."
        )
        return spec
    if autos:
        spec.conversions.append(f"{name}: identity or serial becomes an identity column.")
    return spec


def _identity_type(kind: str, target_type: str) -> bool:
    head = target_type.upper().split("(")[0]
    if kind == MSSQL:
        return head in {"SMALLINT", "INT", "BIGINT", "DECIMAL", "NUMERIC"}
    return head == "NUMBER"


def _primary_key(source_query, table: str) -> list[str]:
    literal = "'" + table.replace("'", "''") + "'"
    rows = source_query(
        "SELECT kcu.column_name FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu "
        "ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema "
        f"AND kcu.table_name = tc.table_name WHERE tc.table_schema = 'public' AND tc.table_name = {literal} "
        "AND tc.constraint_type = 'PRIMARY KEY' ORDER BY kcu.ordinal_position"
    )
    return [str(row.get("column_name")) for row in rows or [] if row.get("column_name")]
